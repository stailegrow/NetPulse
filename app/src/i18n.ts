/**
 * Локализация интерфейса. Ключ — русская строка: так можно переводить постепенно,
 * а непереведённое место остаётся читаемым, а не превращается в «missing.key».
 *
 * Перевод охватывает оболочку приложения: навигацию, списки, таблицы, настройки.
 * Тексты анализатора проблем и журнал событий приходят из ядра и пока только на русском.
 */

export type Lang = "ru" | "en";

let current: Lang = "ru";

export function getLang(): Lang {
  return current;
}

export function setLang(l: Lang) {
  current = l === "en" ? "en" : "ru";
  try {
    document.documentElement.lang = current;
  } catch {
    /* вне браузера */
  }
}

/** Перевод строки на текущий язык. */
export function t(ru: string): string {
  if (current === "ru") return ru;
  return EN[ru] ?? ru;
}

/** Перевод с подстановкой: tf("Готово: {n}", { n: 5 }). */
export function tf(ru: string, vars: Record<string, string | number>): string {
  let out = t(ru);
  for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
  return out;
}

